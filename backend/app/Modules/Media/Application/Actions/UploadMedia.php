<?php

namespace App\Modules\Media\Application\Actions;

use App\Modules\Media\Infrastructure\Jobs\GenerateMediaRenditions;
use App\Modules\Media\Infrastructure\Models\Media;
use App\Modules\Shared\Application\Contracts\AuditTrail;
use App\Modules\Shared\Application\Tenancy\TenantContext;
use App\Modules\Shared\Domain\Exceptions\BusinessRuleViolation;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;

/**
 * Stores an uploaded image under media/<organization>/ with a random name and the
 * extension of its detected MIME type. Uploading the same bytes again returns the
 * existing item. Renditions are generated by a queued job after commit.
 */
class UploadMedia
{
    public function __construct(
        private readonly AuditTrail $audit,
        private readonly TenantContext $tenant,
    ) {}

    /**
     * @return array{media: Media, created: bool}
     */
    public function __invoke(UploadedFile $file, ?string $alt): array
    {
        $checksum = hash_file('sha256', $file->getRealPath());

        $existing = Media::query()->where('checksum', $checksum)->first();
        if ($existing !== null) {
            return ['media' => $existing, 'created' => false];
        }

        $dimensions = @getimagesize($file->getRealPath());
        if ($dimensions === false) {
            throw new BusinessRuleViolation('INVALID_IMAGE', 'The file is not a readable image.');
        }

        $disk = (string) config('media.disk');
        $id = (string) Str::uuid7();
        $path = $file->storeAs('media/'.$this->tenant->requireOrganization(), $id.'.'.($file->guessExtension() ?? 'bin'), $disk);

        try {
            $media = DB::transaction(function () use ($id, $disk, $path, $file, $dimensions, $alt, $checksum) {
                $media = new Media([
                    'disk' => $disk,
                    'path' => $path,
                    'original_name' => mb_substr($file->getClientOriginalName(), 0, 255),
                    'mime_type' => (string) $file->getMimeType(),
                    'size' => (int) $file->getSize(),
                    'width' => $dimensions[0],
                    'height' => $dimensions[1],
                    'alt' => $alt,
                    'checksum' => $checksum,
                ]);
                $media->id = $id;
                $media->save();

                $this->audit->record('media.uploaded', $media, new: ['original_name' => $media->original_name, 'size' => $media->size]);
                GenerateMediaRenditions::dispatch($media->id)->afterCommit();

                return $media;
            });
        } catch (Throwable $e) {
            Storage::disk($disk)->delete($path);
            throw $e;
        }

        return ['media' => $media, 'created' => true];
    }
}
