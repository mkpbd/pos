<?php

namespace App\Modules\Media\Application\Actions;

use App\Modules\Media\Infrastructure\Imaging\GdImageProcessor;
use App\Modules\Media\Infrastructure\Jobs\GenerateMediaRenditions;
use App\Modules\Media\Infrastructure\Models\Media;
use App\Modules\Shared\Application\Contracts\AuditTrail;
use App\Modules\Shared\Application\Tenancy\TenantContext;
use App\Modules\Shared\Domain\Exceptions\BusinessRuleViolation;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;

/**
 * Stores an uploaded image under media/<organization>/ with a random name and the
 * extension of its detected MIME type. Uploading the same bytes again returns the
 * existing item (the checksum is the uploaded file's). Renditions are generated by a
 * queued job after commit.
 *
 * B11: JPEG, PNG and WebP originals larger than RenditionPlan::MAX_SIDE on a side are
 * scaled down (aspect kept), and JPEGs are turned upright by their EXIF orientation; such
 * files are re-encoded without metadata. Everything else is stored byte for byte.
 */
class UploadMedia
{
    public function __construct(
        private readonly AuditTrail $audit,
        private readonly TenantContext $tenant,
        private readonly GdImageProcessor $images,
    ) {}

    /**
     * @return array{media: Media, created: bool}
     */
    public function __invoke(UploadedFile $file, ?string $alt): array
    {
        $checksum = hash_file('sha256', $file->getRealPath());

        $existing = Media::query()->where('checksum', $checksum)->first();
        if ($existing !== null) {
            return ['media' => $existing, 'created' => false];
        }

        $dimensions = @getimagesize($file->getRealPath());
        if ($dimensions === false) {
            throw new BusinessRuleViolation('INVALID_IMAGE', 'The file is not a readable image.');
        }

        $mime = (string) $file->getMimeType();
        $normalized = $this->images->normalizeUpload($file->getRealPath(), $mime, $dimensions[0], $dimensions[1]);

        $disk = (string) config('media.disk');
        $id = (string) Str::uuid7();
        $name = $id.'.'.($file->guessExtension() ?? 'bin');
        $directory = 'media/'.$this->tenant->requireOrganization();
        if ($normalized === null) {
            $path = $file->storeAs($directory, $name, $disk);
            [$size, $width, $height] = [(int) $file->getSize(), $dimensions[0], $dimensions[1]];
        } else {
            $path = $directory.'/'.$name;
            Storage::disk($disk)->put($path, $normalized['bytes']);
            [$size, $width, $height] = [strlen($normalized['bytes']), $normalized['width'], $normalized['height']];
        }

        try {
            $media = DB::transaction(function () use ($id, $disk, $path, $file, $mime, $size, $width, $height, $alt, $checksum, $normalized, $dimensions) {
                $media = new Media([
                    'disk' => $disk,
                    'path' => $path,
                    'original_name' => mb_substr($file->getClientOriginalName(), 0, 255),
                    'mime_type' => $mime,
                    'size' => $size,
                    'width' => $width,
                    'height' => $height,
                    'alt' => $alt,
                    'checksum' => $checksum,
                ]);
                $media->id = $id;
                $media->save();

                $this->audit->record('media.uploaded', $media, new: array_filter([
                    'original_name' => $media->original_name,
                    'size' => $media->size,
                    'optimized_from' => $normalized === null ? null : ['width' => $dimensions[0], 'height' => $dimensions[1], 'size' => (int) $file->getSize()],
                ]));
                GenerateMediaRenditions::dispatch($media->id)->afterCommit();

                return $media;
            });
        } catch (Throwable $e) {
            Storage::disk($disk)->delete($path);
            throw $e;
        }

        return ['media' => $media, 'created' => true];
    }
}
