const BN_DIGITS = '০১২৩৪৫৬৭৮৯'
const digits = (lang: ScreenLang, value: string | number) => (lang === 'bn' ? String(value).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]!) : String(value))

export function wizardWord(lang: ScreenLang, key: WizardWordKey, values: Record<string, string | number> = {}): string {
  const text: string = lang === 'bn' ? bn[key] : en[key]
  return text.replace(/\{(\w+)\}/g, (_, name: string) => (values[name] === undefined ? `{${name}}` : digits(lang, values[name])))
}

export const typeKey = (type: WizardPageType) => `type.${type}` as WizardWordKey
export const goalKey = (goal: WizardGoal) => `goal.${goal}` as WizardWordKey
export const lookKey = (look: WizardLook) => `look.${look}` as WizardWordKey
export const langKey = (language: WizardLanguage) => `lang.${language}` as WizardWordKey
export const aiKey = (status: WizardAiStatus): WizardWordKey | null => (status === 'not_requested' ? null : (`ai.${status}` as WizardWordKey))
