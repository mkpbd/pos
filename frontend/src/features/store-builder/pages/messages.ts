export const MESSAGES: Record<ScreenLang, Record<MessageKey, string>> = { en, bn }

export type MessageValues = Record<string, string | number>

/** A number as the language writes it (Bangla digits in Bangla). */
export function formatNumber(lang: ScreenLang, value: number): string {
  return new Intl.NumberFormat(lang === 'bn' ? 'bn-BD' : 'en-US', { useGrouping: false }).format(value)
}

/** The message in the language with its `{placeholders}` filled (numbers in the language's digits). */
export function translate(lang: ScreenLang, key: MessageKey, values: MessageValues = {}): string {
  const text = MESSAGES[lang][key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name]
    if (value === undefined) return match
    return typeof value === 'number' ? formatNumber(lang, value) : value
  })
}

/** Keys that have `.one` / `.other` forms. */
export type CountKey = MessageKey extends infer K ? (K extends `${infer Base}.one` ? Base : never) : never

/** The count's form of the message (`{count}` filled in). */
export function translateCount(lang: ScreenLang, key: CountKey, count: number, values: MessageValues = {}): string {
  const form = count === 1 ? 'one' : 'other'
  return translate(lang, `${key}.${form}` as MessageKey, { ...values, count })
}

export function isScreenLang(value: unknown): value is ScreenLang {
  return value === 'en' || value === 'bn'
}

/** The date (and time) in the language: Bangla digits and month names in Bangla. */
export function formatDate(lang: ScreenLang, iso: string | null | undefined, withTime = false): string {
  if (!iso) return '—'
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return '—'
  const locale = lang === 'bn' ? 'bn-BD' : undefined
  return withTime ? date.toLocaleString(locale, { dateStyle: 'medium', timeStyle: 'short' }) : date.toLocaleDateString(locale, { dateStyle: 'medium' })
}
