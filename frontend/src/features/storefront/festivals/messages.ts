export const FESTIVAL_MESSAGES: Record<ScreenLang, Record<FestivalMessageKey, string>> = { en, bn }

const BN_DIGITS = '০১২৩৪৫৬৭৮৯'

export const toBanglaDigits = (text: string) => text.replace(/\d/g, (d) => BN_DIGITS[Number(d)]!)

export function festivalText(lang: ScreenLang, key: FestivalMessageKey, values: Record<string, string | number> = {}): string {
  return FESTIVAL_MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = values[name]
    if (value === undefined) return `{${name}}`
    return typeof value === 'number' && lang === 'bn' ? toBanglaDigits(String(value)) : String(value)
  })
}
